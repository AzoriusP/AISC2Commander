def normalize_language(value: object) -> str:
    language = str(value or "").strip()
    return language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def translate(language: str, key: str, **values: object) -> str:
    selected = _TRANSLATIONS.get(normalize_language(language), _TRANSLATIONS[DEFAULT_LANGUAGE])
    template = selected.get(key, _TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key))
    return template.format(**values) if values else template


def load_gui_language(path: Path) -> str:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (FileNotFoundError, OSError, TypeError, ValueError, json.JSONDecodeError):
        return DEFAULT_LANGUAGE
    if not isinstance(payload, dict):
        return DEFAULT_LANGUAGE
    return normalize_language(payload.get("language"))


def save_gui_language(path: Path, language: str) -> str:
    selected = normalize_language(language)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(
        json.dumps({"language": selected}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    temporary.replace(path)
    return selected
